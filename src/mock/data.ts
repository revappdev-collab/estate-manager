export function taskStatus(task: { closed?: boolean; due: string; progress: { status: string }[] }): import("./types").TaskStatus {
  if (task.closed) return "closed";
  const list = task.progress;
  const allDone = list.length > 0 && list.every((p) => p.status === "completed");
  if (allDone) return "completed";
  if (list.some((p) => p.status === "blocked")) return "blocked";
  if (new Date(task.due).getTime() < new Date("2026-11-11T16:00:00.000Z").getTime()) return "overdue";
  if (list.some((p) => p.status === "in_progress" || p.status === "completed")) return "in_progress";
  if (list.some((p) => p.status === "acknowledged")) return "acknowledged";
  return "new";
}
